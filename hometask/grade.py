student_grade = int(input("Enter student grade"))

if student_grade >= 90 and student_grade <= 100:
		print("A")
if student_grade >= 80 and student_grade <= 85:
		print("B")
elif student_grade >= 65 and student_grade <= 79:
		print("C")
elif student_grade >= 40 and student_grade <= 54:
		print("D")
elif student_grade < 40:
		print("E") 

